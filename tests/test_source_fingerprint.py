"""Build identity must ignore a transient standalone protocol lockfile."""

import tempfile
import unittest
from pathlib import Path

from scripts.source_fingerprint import fingerprint


class SourceFingerprintTests(unittest.TestCase):
    def test_core_identity_uses_its_build_lock_not_protocol_test_lock(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name in (
                "scripts/source_fingerprint.py",
                "build_support.rs",
                "lib/src/lib.rs",
                "lib/Cargo.toml",
                "lib/Cargo.lock",
                "protocol/src/lib.rs",
                "protocol/Cargo.toml",
            ):
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(name)

            original = fingerprint(root, "core")
            (root / "protocol/Cargo.lock").write_text("generated by standalone test")
            self.assertEqual(fingerprint(root, "core"), original)

            (root / "lib/Cargo.lock").write_text("changed build dependencies")
            self.assertNotEqual(fingerprint(root, "core"), original)


if __name__ == "__main__":
    unittest.main()
