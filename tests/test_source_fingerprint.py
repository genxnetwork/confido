"""Build identity includes the shared workspace, not transient crate locks."""

import tempfile
import unittest
from pathlib import Path

from scripts.source_fingerprint import fingerprint


class SourceFingerprintTests(unittest.TestCase):
    def test_core_identity_uses_shared_workspace_lock(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name in (
                "scripts/source_fingerprint.py",
                "build_support.rs",
                "lib/src/lib.rs",
                "lib/Cargo.toml",
                "lib/Cargo.lock",
                "evidence/Cargo.toml",
                "evidence/Cargo.lock",
                "evidence/protocol/src/lib.rs",
                "evidence/protocol/Cargo.toml",
                "evidence/core/src/lib.rs",
                "evidence/core/Cargo.toml",
            ):
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(name)

            original = fingerprint(root, "core")
            (root / "evidence/protocol/Cargo.lock").write_text("generated by standalone test")
            self.assertEqual(fingerprint(root, "core"), original)

            (root / "lib/Cargo.lock").write_text("changed build dependencies")
            self.assertNotEqual(fingerprint(root, "core"), original)

            (root / "lib/Cargo.lock").write_text("lib/Cargo.lock")
            (root / "evidence/core/src/lib.rs").write_text("changed shared checks")
            self.assertNotEqual(fingerprint(root, "core"), original)


if __name__ == "__main__":
    unittest.main()
